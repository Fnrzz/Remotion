// Run from the project root: node scripts/analyze-character-voiceover.mjs
// Bake a deterministic motion envelope; playback never analyzes audio in real time.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const source = "assets/audio/voiceover2.mp3";
const sampleRate = 16000;
const fps = 30;
const pcm = execFileSync(
  "ffmpeg",
  [
    "-v",
    "error",
    "-i",
    `public/${source}`,
    "-f",
    "s16le",
    "-ac",
    "1",
    "-ar",
    String(sampleRate),
    "pipe:1",
  ],
  { maxBuffer: 16 * 1024 * 1024 },
);
const sampleCount = pcm.length / 2;
const frameCount = Math.ceil((sampleCount / sampleRate) * fps);
const rms = Array.from({ length: frameCount }, (_, frame) => {
  const from = Math.floor((frame / fps) * sampleRate);
  const to = Math.min(
    sampleCount,
    Math.floor(((frame + 1) / fps) * sampleRate),
  );
  let sum = 0;
  for (let sample = from; sample < to; sample++) {
    const amplitude = pcm.readInt16LE(sample * 2) / 32768;
    sum += amplitude * amplitude;
  }
  return Math.sqrt(sum / Math.max(1, to - from));
});
const sorted = [...rms].sort((a, b) => a - b);
const ceiling = Math.max(0.01, sorted[Math.floor(sorted.length * 0.95)]);
const normalized = rms.map((value) =>
  Math.min(1, Math.max(0, (value / ceiling - 0.04) / 0.96)),
);
let smooth = 0;
let transient = 0;
const levels = [];
const accents = [];
for (let frame = 0; frame < frameCount; frame++) {
  const raw = normalized[frame];
  smooth += (raw - smooth) * (raw > smooth ? 0.58 : 0.24);
  const onset = Math.max(0, raw - (normalized[frame - 1] ?? 0) - 0.08);
  transient = Math.max(Math.min(1, onset * 2.5), transient * 0.58);
  levels.push(Number(smooth.toFixed(3)));
  accents.push(Number(transient.toFixed(3)));
}
writeFileSync(
  "src/data/character-audio.ts",
  "// Generated by scripts/analyze-character-voiceover.mjs.\n" +
    "export const CHARACTER_AUDIO = " +
    JSON.stringify({ source, fps, levels, accents }) +
    ";\n",
);
console.log(`Baked ${frameCount} frames of character motion from ${source}.`);
